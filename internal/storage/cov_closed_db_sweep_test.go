// TestCovAuxHelpers covers pure helpers whose only branches matter for the
// remaining coverage: page normalisation, merge windows and cache eviction.
func TestCovAuxHelpers(t *testing.T) {
	limit, offset := normalizeAIHistoryPage(-1, -5)
	require.Equal(t, 50, limit)
	require.Equal(t, 0, offset)
	limit, offset = normalizeAIHistoryPage(1000, 20)
	require.Equal(t, 50, limit, "out-of-range limits fall back to the default")
	require.Equal(t, 20, offset)
	limit, offset = normalizeAIHistoryPage(200, 0)
	require.Equal(t, 200, limit)
	require.Equal(t, 0, offset)
	limit, offset = normalizeAIHistoryPage(10, 20)
	require.Equal(t, 10, limit)
	require.Equal(t, 20, offset)

	where, args := aiHistoryWhere("cam-1", "person")
	require.Contains(t, where, "camera_id = ?")
	require.Contains(t, where, "detections_json LIKE ?")
	require.Len(t, args, 2)
	require.Equal(t, "%person%", args[1])
	where, args = aiHistoryWhere("", "")
	require.Empty(t, where)
	require.Empty(t, args)

	require.Equal(t, int64(60), mergeWindowSeconds(time.Minute))
	require.Equal(t, int64(3600), mergeWindowSeconds(time.Hour))
	require.Equal(t, int64(3600), mergeWindowSeconds(500*time.Millisecond), "sub-minute windows fall back to one hour")
	require.Equal(t, int64(90), mergeWindowSeconds(90*time.Second))

	require.ErrorIs(t, errors.Unwrap(conflict()), nil)

	require.Equal(t, 1, boolToInt(true))
	require.Zero(t, boolToInt(false))
	require.Equal(t, 1, boolToDBInt(true))
	require.Zero(t, boolToDBInt(false))
}

// TestCovRecordingsCacheEdges covers clone/filter-key and manual cache ops.
func TestCovRecordingsCacheEdges(t *testing.T) {
	db := newTestDB(t)

	require.Empty(t, cloneRecordings(nil))
	source := []model.Recording{{ID: "a"}, {ID: "b"}}
	cloned := cloneRecordings(source)
	require.Equal(t, source, cloned)
	cloned[0].ID = "changed"
	require.Equal(t, "a", source[0].ID, "clone does not alias the input")

	enabled := true
	keyAll := recordingFilterKey(model.RecordingFilter{CameraID: "cam-1"}, true)
	keyPage := recordingFilterKey(model.RecordingFilter{CameraID: "cam-1"}, false)
	require.NotEqual(t, keyAll, keyPage, "paging is part of the key only when asked")
	keyWithFlag := recordingFilterKey(model.RecordingFilter{CameraID: "cam-1", Archived: &enabled}, true)
	require.NotEqual(t, keyAll, keyWithFlag)
	require.NotEqual(t,
		recordingFilterKey(model.RecordingFilter{StreamID: "a"}, true),
		recordingFilterKey(model.RecordingFilter{StreamID: "b"}, true))

	gen := db.recordingsCacheGen()
	db.storeListRecordings(keyAll, source, gen)
	cached, ok := db.lookupListRecordings(keyAll)
	require.True(t, ok)
	require.Equal(t, source, cached)
	cached[0].ID = "mutated"
	again, ok := db.lookupListRecordings(keyAll)
	require.True(t, ok)
	require.Equal(t, "a", again[0].ID, "the cache hands out copies")

	db.storeCountRecordings(keyAll, 2, gen)
	count, ok := db.lookupCountRecordings(keyAll)
	require.True(t, ok)
	require.Equal(t, 2, count)

	// A new generation invalidates both entries without clearing the map first.
	db.invalidateRecordingsCache()
	_, ok = db.lookupListRecordings(keyAll)
	require.False(t, ok)
	_, ok = db.lookupCountRecordings(keyAll)
	require.False(t, ok)
	require.Greater(t, db.recordingsCacheGen(), gen)
}
